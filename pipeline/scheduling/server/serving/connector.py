"""The harness connector: the agent tier's privileged surface as
authenticated tools, hosted by this server (harness-connector
plan, Steps 1–3; contract annex in .plans/).

Design points, all load-bearing:

- No authority crosses the connector. There is no tool that
  approves a permission, pushes, acquires a lease, or writes a
  calendar. The tools are the agent tier's privileged calls,
  enumerated in the annex. The retired approval sweeper's
  compatibility tools (its state file read/write and the
  nudge-ledger append, with the retired schema inlined here)
  left at the consolidation's step S3 (plan §10.2, ruled):
  the sweeper's records stay on disk, unread by the pipeline.
- Caller identity derives from a per-caller bearer token. The
  server stores only SHA-256 hashes, in the `connector.callers`
  object of the untracked live config; the registry is read
  fresh from that file on every call, so minting or revoking a
  caller needs no restart. Raw tokens are generated by the
  `bin/sched connector-token` admin verb, shown once, and
  delivered to venues through the secure route — never a
  notebook, never a chat.
- Every call is recorded in the ledger as kind `connector`
  with caller, tool, scope, and status — including refusals.
- Direct tools execute in the server process by wrapping the
  in-tree cores (outbox ack, the workbench's served API).
  Chat and pending-permission
  access are Muse runtime agent tools with no process-level
  form, so those tools are BRIDGED: the call records a request
  in the bridge queue (the pipeline dispatch substrate,
  `dispatch.bridge` — contract 05), a home-side agent holding
  the runtime tools fulfills it and posts the result back
  through the bridge-scope endpoints, and the requester polls
  for it. Attribution is preserved end to end; bridged tools
  are asynchronous by contract.
- A bridged call may carry an `envelope_id` (the ferry
  request file's stem, sent by the relay as a sibling of
  `args` in the POST body). The id is stored on the bridge
  record, and a second enqueue with the same (caller,
  envelope_id) returns the existing record instead of
  queueing a twin — idempotency at the boundary, so a
  transport-level retry of one performed call can never
  double-queue (a duplicated chat_send would double-send).
"""
import hashlib
import hmac
import json
import os
import urllib.error
import urllib.request

from dispatch import bridge

SCOPES = ("read", "write-state", "send", "bridge", "exec")


class ToolError(Exception):
    def __init__(self, name, detail="", status=400):
        super().__init__(detail or name)
        self.name = name
        self.detail = detail or name
        self.status = status


# ---------------------------------------------------------------- auth

def load_callers(home):
    """The caller registry, read fresh from the live config file
    on every call: {name: {"token_sha256": hex, "scopes": [...]}}.
    A missing or malformed registry means no callers — every call
    is refused — never a permissive default."""
    path = os.path.join(home, "config.json")
    try:
        with open(path, encoding="utf-8") as fh:
            data = json.load(fh)
    except (OSError, ValueError):
        return {}
    section = data.get("connector") if isinstance(data, dict) else None
    callers = section.get("callers") if isinstance(section, dict) else None
    if not isinstance(callers, dict):
        return {}
    clean = {}
    for name, spec in callers.items():
        if not isinstance(spec, dict):
            continue
        digest = spec.get("token_sha256")
        scopes = [s for s in (spec.get("scopes") or []) if s in SCOPES]
        if isinstance(digest, str) and len(digest) == 64 and scopes:
            clean[name] = {"token_sha256": digest, "scopes": scopes}
    return clean


def authenticate(values, token):
    """Return (caller_name, scopes) for a bearer token, or None."""
    if not token:
        return None
    digest = hashlib.sha256(token.encode("utf-8")).hexdigest()
    for name, spec in load_callers(values["home"]).items():
        if hmac.compare_digest(digest, spec["token_sha256"]):
            return name, spec["scopes"]
    return None


def health_summary(values):
    """What /health may say about the connector: caller names and
    scopes only — never hashes, never tokens."""
    return {"callers": {name: spec["scopes"]
                        for name, spec in sorted(load_callers(values["home"]).items())}}


# ---------------------------------------------------------------- paths

def _bridge_dir(values):
    return os.path.join(values["home"], "state", "connector-bridge")


# ---------------------------------------------------------------- direct tools

def _tool_ping_ack(engine, values, caller, args):
    ping_id = args.get("ping_id")
    if not isinstance(ping_id, str) or not ping_id:
        raise ToolError("bad_args", "ping_id is required")
    if engine.outbox is None:
        raise ToolError("tool_failed", "outbox unavailable", status=503)
    ping = engine.outbox.ack(ping_id)
    if ping is None:
        raise ToolError("no_such_ping", ping_id, status=404)
    return {"ping": ping}


def _tool_workbench_read(engine, values, caller, args):
    path = args.get("path")
    if not isinstance(path, str) or not path.startswith("/api/"):
        raise ToolError("bad_args", "path must be a served /api/ path (Step 4 seam)")
    base = values.get("workbench_base_url") or "http://127.0.0.1:8792"
    req = urllib.request.Request(base.rstrip("/") + path, method="GET")
    # The viewer's first hit after an idle stretch can take
    # several seconds (its sweep warms lazily); a refused
    # connection is a down viewer and fails at once, a timeout
    # earns exactly one retry before the enumerable error.
    body = status = None
    for attempt in (1, 2):
        try:
            with urllib.request.urlopen(req, timeout=15) as resp:
                body = resp.read().decode("utf-8", errors="replace")
                status = resp.status
            break
        except (urllib.error.URLError, OSError) as exc:
            if "timed out" not in str(exc) or attempt == 2:
                raise ToolError("workbench_unavailable", str(exc), status=502)
    try:
        return {"status": status, "body": json.loads(body)}
    except ValueError:
        return {"status": status, "body": body}


DIRECT_TOOLS = {
    "ping_ack": ("write-state", _tool_ping_ack),
    "workbench_read": ("read", _tool_workbench_read),
}

# Bridged tools: name -> scope. Args are validated at fulfillment
# by the home agent holding the runtime tools; the bridge carries
# them verbatim under the requester's attribution.
BRIDGED_TOOLS = {
    "chat_list": "read",
    "chat_tail": "read",
    "permissions_list": "read",
    "permissions_history": "read",
    "chat_send": "send",
}


def tool_scopes():
    scopes = {name: scope for name, (scope, _fn) in DIRECT_TOOLS.items()}
    scopes.update(BRIDGED_TOOLS)
    scopes.update({"bridge_poll": "bridge", "bridge_fulfill": "bridge"})
    return scopes


# ---------------------------------------------------------------- bridge queue

# The queue itself is the dispatch substrate's
# (`dispatch.bridge`, contract 05): record form, envelope
# idempotency, poll, and fulfill live there. This module
# keeps the tool surface over it — scopes, and the
# ToolError translation of the queue's refusals.

def _read_request(values, request_id):
    return bridge.read_request(_bridge_dir(values), request_id)


def _bridge_poll(engine, values, caller, args):
    return {"requests": bridge.poll_queued(_bridge_dir(values))}


def _bridge_fulfill(engine, values, caller, args):
    request_id = args.get("request_id")
    try:
        record = bridge.fulfill(
            _bridge_dir(values), request_id, caller,
            ok=bool(args.get("ok")), result=args.get("result"),
            error=args.get("error"))
    except ValueError as exc:
        raise ToolError("bad_args", str(exc), status=409) from exc
    if record is None:
        raise ToolError("no_such_request", str(request_id), status=404)
    return {"request_id": request_id, "status": record["status"]}


# ---------------------------------------------------------------- dispatch

def call_tool(engine, values, caller, scopes, tool, args, envelope_id=None):
    """Run one authenticated call. Returns (http_status, payload).
    The HTTP layer ledgers every outcome, including refusals
    raised here as ToolError."""
    if not isinstance(args, dict):
        raise ToolError("bad_args", "args must be a JSON object")
    if tool in DIRECT_TOOLS:
        scope, fn = DIRECT_TOOLS[tool]
        if scope not in scopes:
            raise ToolError("scope_refused", f"{tool} needs scope {scope}", status=403)
        return 200, {"ok": True, "tool": tool, "result": fn(engine, values, caller, args)}
    if tool in BRIDGED_TOOLS:
        scope = BRIDGED_TOOLS[tool]
        if scope not in scopes:
            raise ToolError("scope_refused", f"{tool} needs scope {scope}", status=403)
        # No authority crosses here by construction: a queued
        # send is chat text — a permission decision is a runtime
        # card action, and no tool in this contract performs one.
        if envelope_id is not None:
            if not bridge.valid_envelope_id(envelope_id):
                raise ToolError(
                    "bad_args",
                    "envelope_id must be 1-128 chars of [A-Za-z0-9._-]",
                    status=400)
            record, deduped = bridge.enqueue_idempotent(
                _bridge_dir(values), caller, tool, args, envelope_id)
            if deduped:
                return 200, {"ok": True, "tool": tool,
                             "request_id": record["id"],
                             "status": record["status"],
                             "deduped": True, "envelope_id": envelope_id}
            return 202, {"ok": True, "tool": tool,
                         "request_id": record["id"], "status": "queued",
                         "envelope_id": envelope_id}
        record = bridge.enqueue(_bridge_dir(values), caller, tool, args)
        return 202, {"ok": True, "tool": tool, "request_id": record["id"],
                     "status": "queued"}
    if tool in ("bridge_poll", "bridge_fulfill"):
        if "bridge" not in scopes:
            raise ToolError("scope_refused", f"{tool} needs scope bridge", status=403)
        fn = _bridge_poll if tool == "bridge_poll" else _bridge_fulfill
        return 200, {"ok": True, "tool": tool, "result": fn(engine, values, caller, args)}
    raise ToolError("unknown_tool", tool, status=404)


def fetch_result(engine, values, caller, scopes, request_id):
    record = _read_request(values, request_id)
    if record is None:
        raise ToolError("no_such_request", request_id, status=404)
    if record.get("caller") != caller and "bridge" not in scopes:
        raise ToolError("scope_refused", "not the requesting caller", status=403)
    return (200 if record["status"] != "queued" else 202), {
        "ok": True, "request_id": request_id, "status": record["status"],
        "result": record.get("result"), "error": record.get("error")}
