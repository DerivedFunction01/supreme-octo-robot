export function counts(h: MockHost) {
  const terminal = new Set(
    STATUS_VOCABULARY.filter((r) => r.terminal).map((r) => r.code),
  );
  return {
    mockupsInTriage: h.s.db.entries.filter(
      (e) => e.project === "spec-driven-starter" && e.kind === "mockup" && e.review === "in-triage" && !e.archived,
    ).length,
    boardDoing: h.board().filter((c) => c.lane === "doing").length,
    inboxAwaiting: h.s.db.messages.filter((m) => m.disposition === null).length,
    goalsActive: h.s.db.goals.filter(
      (g) => !g.lastPost || !terminal.has(g.lastPost.status_code),
    ).length,
  };
}
